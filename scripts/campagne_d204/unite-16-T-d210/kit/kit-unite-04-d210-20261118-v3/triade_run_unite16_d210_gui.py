def ligne_m1_existe(atelier):
    """LA LIGNE M1 de CE kit vit-elle déjà au livraisons.csv de
    l'atelier choisi ? (l'idempotence : une ligne par run compté, le
    livre ne ment jamais — jamais deux fois.)"""
    chemin = pathlib.Path(atelier) / "livraisons.csv"
    if not chemin.is_file():
        return False
    for ligne in chemin.read_text(encoding="utf-8",
                                  errors="replace").splitlines():
        if ligne.startswith(NOM_LIVRAISON_M1 + ","):
            return True
