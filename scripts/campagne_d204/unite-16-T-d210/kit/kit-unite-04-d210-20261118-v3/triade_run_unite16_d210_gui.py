        def tout_lancer(self):
            if self.occupe_flag:
                return
            if not getattr(self, "verrou_vert", False):
                messagebox.showinfo(
                    "TRIADE", "le verrou n'est pas VERT — le GUI refuse "
                    "de lancer (fail-closed)")
                return
            atelier = self.etat.get("atelier")
            if atelier:
                vert, _ = verifier_atelier(atelier)
                if not vert:
                    messagebox.showinfo(
                        "TRIADE — l'atelier diverge",
                        "L'ATELIER CHOISI diverge (les QUATRE registres se "
                        "recoupent à l'onglet 4·LIVRE) — le GUI refuse de "
                        "lancer : choisissez le BON dossier de l'atelier ; "
                        "le livre ne se mettrait pas à jour en silence.")
                    return
                if ligne_m1_existe(atelier):
                    messagebox.showinfo(
                        "TRIADE — le run déjà compté au livre",
                        "LA LIGNE " + NOM_LIVRAISON_M1 + " VIT DÉJÀ au "
                        "livraisons.csv de l'atelier choisi — le run vécu "
                        "est COMPTÉ (M1) : le livre ne ment jamais, jamais "
                        "deux fois. Le rejeu diagnostic (§ 7 : le rejouage "
                        "n'est PAS une livraison) se vit au bouton "
                        "REJOUER — il ne porte AUCUNE ligne au livre.")
                    return
            self.occupe(True)
            self.console.delete("1.0", "end")
            self.etape_statut(
                "TOUT LANCER", "parti",
                "le verrou → le run → la collecte → "
                + ("LE LIVRE (à l'atelier choisi)" if atelier
                   else "le livre (l'atelier n'est PAS choisi : le geste à "
                        "la main du guide-344 § 2-3 demeure)")
                + " → le témoin")
            self.console_insert("=== TOUT LANCER — " + maintenant_local()
                                + " : le verrou recoupé, le run part, la "
                                "collecte suivra, le livre "
                                + ("se met à jour à l'ATELIER CHOISI"
                                   if atelier else "demeure à votre main "
                                   "(l'atelier n'est pas choisi)")
                                + ", le témoin est à VOTRE MAIN (D99) ===")
            debut_geste = dt.datetime.now()

            def travail():
                self._geste_run()
                self._geste_collecte(self.etat["contexte"])
                if atelier:
                    self._geste_livre(atelier, debut_geste)

            self.file.partir(travail)

