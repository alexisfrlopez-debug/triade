            self.bouton_zip.pack(side="right", padx=4)
            titre = ttk.Label(bandeau,
                              text=("TRIADE — l'unité 04 D210 "
                                    "(loupe-16 saisie × bras T)"),
                              font=("TkDefaultFont", 13, "bold"))
            titre.pack(side="left")
