def ecrire_au_livre(atelier, contexte, debut_geste, fin_geste):
    """LE GESTE DU LIVRE (durant le run — l'édition v2 du commandement)
    : LA LIGNE M1 appendée à livraisons.csv, LA LIGNE M3 appendée au
    carnet — le verrou de l'atelier recoupé AVANT, le doublon REFUSÉ
    nommé, l'écriture des DEUX registres protégée (l'état nommé si le
    disque refuse), AUCUNE autre ligne touchée, le LF final posé, et
    defauts.csv avec journal-ouverture.txt JAMAIS touchés (leurs sha
    recoupés après le geste, INTACTS — la preuve au retour). Retour
    {m1, m3, shas} — les sha des QUATRE registres après le geste."""
    atelier = pathlib.Path(atelier)
    vert, resultats = verifier_atelier(atelier)
    if not vert:
        ecart = " ; ".join(r["message"] for r in resultats if not r["vert"])
        raise ErreurRun("L'ATELIER CHOISI DIVERGE — le livre ne se met "
                        "PAS à jour : " + ecart + " ; votre main demeure "
                        "(le guide-344 § 2-3), renvoyez l'écart au labo.")
    if ligne_m1_existe(atelier):
        raise ErreurRun("LA LIGNE " + NOM_LIVRAISON_M1 + " VIT DÉJÀ au "
                        "livraisons.csv de l'atelier choisi — le run vécu "
                        "est COMPTÉ (M1) : le livre ne ment jamais, jamais "
                        "deux fois ; le rejeu diagnostic (§ 7) se vit au "
                        "bouton REJOUER, il ne porte AUCUNE ligne.")
    date_run = debut_geste.strftime("%Y-%m-%d")
    ligne_m1 = fabriquer_ligne_m1(contexte, date_run)
    ligne_m3 = fabriquer_ligne_m3(debut_geste, fin_geste)
    shas_avant = {nom: sha256_fichier(atelier / nom)
                  for nom, _ in REGISTRES_ATELIER}
    try:
        for nom, ligne in (("livraisons.csv", ligne_m1),
                           ("carnet_temps_humain.csv", ligne_m3)):
            chemin = atelier / nom
            brut = chemin.read_bytes()
            if not brut.endswith(b"\n"):
                brut += b"\n"  # le LF final posé (le guide-313)
            chemin.write_bytes(brut + ligne.encode("utf-8") + b"\n")
    except OSError as e:
        raise ErreurRun("l'écriture au livre a refusé (" + type(e).__name__
                        + " : " + str(e) + ") — l'état des DEUX registres "
                        "se vérifie AU BLOC-NOTES (jamais Excel) avant "
                        "tout renvoi ; la console du run demeure, le "
                        "témoin demeure, votre main reprend le geste.")
    shas = {nom: sha256_fichier(atelier / nom)
            for nom, _ in REGISTRES_ATELIER}
    for nom in ("defauts.csv", "journal-ouverture.txt"):
        if shas[nom] != shas_avant[nom]:
            raise ErreurRun("le geste du livre a touché " + nom + " — "
                            "JAMAIS (D202 : l'écart nommé, la consigne "
                            "au labo) ; l'état du registre se recoupe au "
                            "bloc-notes.")
    return {"m1": ligne_m1, "m3": ligne_m3, "shas": shas}


