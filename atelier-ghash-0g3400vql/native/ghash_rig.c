static inline unsigned long long rdtscp32(void) {
    unsigned aux, lo, hi;
    __asm__ volatile("rdtscp" : "=a"(lo), "=d"(hi), "=c"(aux) :: "memory");
    return ((unsigned long long)hi << 32) | lo;
}
