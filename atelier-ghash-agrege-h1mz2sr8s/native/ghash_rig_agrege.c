static inline unsigned long long rdtscp32(void) {
    unsigned aux, lo, hi;
    __asm__ volatile("rdtscp" : "=a"(lo), "=d"(hi), "=c"(aux) :: "memory");
    return ((unsigned long long)hi << 32) | lo;
}
static uint64_t xs = 20261121ULL;
static inline uint64_t nxt64(void) {
    xs ^= xs << 13; xs ^= xs >> 7; xs ^= xs << 17;
    return xs;
}
static void med_iqr(unsigned long long *cyc, int n,
                    unsigned long long *med, unsigned long long *iqr) {
    for (int i = 1; i < n; i++) {
        unsigned long long v = cyc[i];
        int j = i - 1;
        while (j >= 0 && cyc[j] > v) { cyc[j+1] = cyc[j]; j--; }
        cyc[j+1] = v;
    }
    *med = (cyc[n/2-1] + cyc[n/2]) / 2;
    *iqr = cyc[3*n/4] - cyc[n/4];
}
#define N_MES 20
static unsigned long long cyc[N_MES];
#define MESURE(nom, div, expr) do { \
    for (int r = 0; r < 3; r++) { (void)(expr); } \
    for (int r = 0; r < N_MES; r++) { \
        unsigned long long t0 = rdtscp32(); \
        (void)(expr); \
        cyc[r] = rdtscp32() - t0; \
    } \
    unsigned long long med, iqr; med_iqr(cyc, N_MES, &med, &iqr); \
    printf("MESURE %-22s %llu %llu %.4f %.4f\n", nom, med, iqr, \
           (double)med/(double)(div), (double)iqr/(double)(div)); \
} while(0)

/* ---- (A) LA COMPOSITION GCM ENTRELACÉE : le CTR porteuse par GROUPES DE
   4, le XOR par mots de 64 bits, le GHASH AGRÉGÉ du groupe (l'accumulateur
   replié dans le premier bloc), la queue par-bloc au scellé, l'étiquette.
   La table des puissances tordues EMBARQUÉE (tabletw — dérivée par le juge
   python du H openssl, recoupée au runtime) ---- */
static int rig_h_printed = 0;
static void gcm_agrege(const unsigned char *cle, const unsigned char *nonce,
                       const unsigned char *clair, size_t n,
                       const unsigned char *aad, size_t na,
                       unsigned char *ct, unsigned char *tag, int pcl) {
    unsigned char rk[176];
    appeler_msx64(56512, (unsigned long)cle, (unsigned long)rk, 0, 0, 0);
    /* H = E(K, 0) ; EJ0 = E(K, J0) : la porteuse, DEUX blocs, UN appel */
    unsigned char in0[32], out0[32];
    memset(in0, 0, 16);
    memcpy(in0 + 16, nonce, 12); in0[28] = 0; in0[29] = 0; in0[30] = 0; in0[31] = 1;
    appeler_msx64(60416, (unsigned long)rk, (unsigned long)in0, (unsigned long)out0, 2, 0);
    unsigned char H[16], EJ0[16];
    memcpy(H, out0, 16); memcpy(EJ0, out0 + 16, 16);
    if (!rig_h_printed) {
        printf("RIG-H ");
        for (int i = 0; i < 16; i++) printf("%02x", H[i]);
        printf("\n");
        rig_h_printed = 1;
    }
    unsigned char Y[16]; memset(Y, 0, 16);
    unsigned char tmp[16];
    /* (1) l'AAD : par-bloc au scellé (le pad à zéro du dernier bloc) */
    if (na > (1u << 20)) return;   /* le garde-fou — jamais pris ici */
    size_t nap = (na + 15) / 16 * 16;
    unsigned char *aadp = malloc(nap ? nap : 16);
    memset(aadp, 0, nap ? nap : 16);
    if (na) memcpy(aadp, aad, na);
    for (size_t b = 0; b < nap / 16; b++) {
        for (int i = 0; i < 16; i++) tmp[i] = Y[i] ^ aadp[16*b + i];
        appeler_r10(57280, 0x500800, (unsigned long)tmp, (unsigned long)H, 0, 0, 0);
        memcpy(Y, (void*)0x500800, 16);
    }
    free(aadp);
    /* (2) LE CTR ENTRELACÉ avec le GHASH agrégé — GROUPES DE 4 BLOCS
       COMPLETS (g = le COMPTE DE BLOCS traités) */
    size_t nb = n ? (n + 15) / 16 : 0;
    uint32_t ctr = 2;   /* le CTR démarre à inc32(J0) = J0+1 */
    size_t g = 0;
    for (; 16*(g + 4) <= n; g += 4) {
        unsigned char cbs[64], ks[64], blocs[64];
        for (int b = 0; b < 4; b++) {
            memcpy(cbs + 16*b, nonce, 12);
            cbs[16*b+12] = (unsigned char)(ctr >> 24); cbs[16*b+13] = (unsigned char)(ctr >> 16);
            cbs[16*b+14] = (unsigned char)(ctr >> 8);  cbs[16*b+15] = (unsigned char)ctr;
            ctr++;
        }
        appeler_msx64(60416, (unsigned long)rk, (unsigned long)cbs, (unsigned long)ks, 4, 0);
        for (int i = 0; i < 8; i++)
            ((uint64_t*)(ct + 16*g))[i] = ((const uint64_t*)(clair + 16*g))[i] ^ ((uint64_t*)ks)[i];
        /* le GHASH agrégé du groupe : X1 = Y ⊕ ct1, puis ct2..ct4 */
        for (int i = 0; i < 2; i++)
            ((uint64_t*)blocs)[i] = ((const uint64_t*)(ct + 16*g))[i] ^ ((uint64_t*)Y)[i];
        for (int i = 2; i < 8; i++)
            ((uint64_t*)blocs)[i] = ((const uint64_t*)(ct + 16*g))[i];
        appeler_r10(62208, 0x500800, (unsigned long)blocs,
                    (unsigned long)tabletw, (unsigned long)tabletw, 0, pcl ? 1 : 0);
        memcpy(Y, (void*)0x500800, 16);
    }
    /* (3) la queue du CT (les blocs restants, le dernier PARTIEL paddé à
       zéro) : par-bloc au scellé */
    size_t reste = nb - g;
    if (reste) {
        unsigned char cbs[48], ks[48];
        for (size_t b = 0; b < reste; b++) {
            memcpy(cbs + 16*b, nonce, 12);
            cbs[16*b+12] = (unsigned char)(ctr >> 24); cbs[16*b+13] = (unsigned char)(ctr >> 16);
            cbs[16*b+14] = (unsigned char)(ctr >> 8);  cbs[16*b+15] = (unsigned char)ctr;
            ctr++;
        }
        appeler_msx64(60416, (unsigned long)rk, (unsigned long)cbs, (unsigned long)ks, reste, 0);
        size_t fin = n - 16*g;
        for (size_t i = 0; i < fin; i++) ct[16*g + i] = clair[16*g + i] ^ ks[i];
        for (size_t b = 0; b < reste; b++) {
            size_t take = n - 16*(g + b);
            if (take > 16) take = 16;
            for (int i = 0; i < 16; i++)
                tmp[i] = Y[i] ^ (i < (int)take ? ct[16*(g + b) + i] : 0);
            appeler_r10(57280, 0x500800, (unsigned long)tmp, (unsigned long)H, 0, 0, 0);
            memcpy(Y, (void*)0x500800, 16);
        }
    }
    /* (4) le bloc L (les longueurs) + (5) l'étiquette */
    uint64_t ab = (uint64_t)na * 8, cb = (uint64_t)n * 8;
    unsigned char L[16]; memset(L, 0, 16);
    for (int i = 0; i < 8; i++) L[i] = (unsigned char)(ab >> (56 - 8*i));
    for (int i = 0; i < 8; i++) L[8 + i] = (unsigned char)(cb >> (56 - 8*i));
    for (int i = 0; i < 16; i++) tmp[i] = Y[i] ^ L[i];
    appeler_r10(57280, 0x500800, (unsigned long)tmp, (unsigned long)H, 0, 0, 0);
    memcpy(Y, (void*)0x500800, 16);
    for (int i = 0; i < 16; i++) tag[i] = EJ0[i] ^ Y[i];
}

/* ---- (B) la composition PAR-BLOC du v13 (la structure exacte du pilote
   0g3400vql : le CTR entier en un appel, le XOR octet par octet, le GHASH
   par bloc au couloir/scellé) — la baseline même-session ---- */
static void gcm_perbloc(unsigned long fn_ghash, int pclmul,
                        const unsigned char *cle, const unsigned char *nonce,
                        const unsigned char *clair, size_t n,
                        const unsigned char *aad, size_t na,
                        unsigned char *ct, unsigned char *tag) {
    unsigned char rk[176];
    appeler_msx64(56512, (unsigned long)cle, (unsigned long)rk, 0, 0, 0);
    unsigned char in0[32], out0[32];
    memset(in0, 0, 16);
    memcpy(in0 + 16, nonce, 12); in0[28] = 0; in0[29] = 0; in0[30] = 0; in0[31] = 1;
    appeler_msx64(60416, (unsigned long)rk, (unsigned long)in0, (unsigned long)out0, 2, 0);
    unsigned char H[16], EJ0[16];
    memcpy(H, out0, 16); memcpy(EJ0, out0 + 16, 16);
    unsigned char *cbs = malloc(16 * (n ? (n + 15) / 16 : 1));
    uint32_t ctr = 2;
    for (size_t b = 0; b < (n ? (n + 15) / 16 : 1); b++) {
        memcpy(cbs + 16*b, nonce, 12);
        cbs[16*b+12] = (unsigned char)(ctr >> 24); cbs[16*b+13] = (unsigned char)(ctr >> 16);
        cbs[16*b+14] = (unsigned char)(ctr >> 8);  cbs[16*b+15] = (unsigned char)ctr;
        ctr++;
    }
    size_t nb = n ? (n + 15) / 16 : 0;
    unsigned char *ks = malloc(16 * (nb ? nb : 1));
    if (nb) appeler_msx64(60416, (unsigned long)rk, (unsigned long)cbs, (unsigned long)ks, nb, 0);
    for (size_t i = 0; i < n; i++) ct[i] = clair[i] ^ ks[i];
    unsigned char *flux = malloc(16 * (na/16 + nb + 8 + 2));
    unsigned char *pc = flux;
    for (size_t i = 0; i < na; i++) *pc++ = aad[i];
    while ((pc - flux) % 16) *pc++ = 0;
    for (size_t i = 0; i < n; i++) *pc++ = ct[i];
    while ((pc - flux) % 16) *pc++ = 0;
    uint64_t ab = (uint64_t)na * 8, cb = (uint64_t)n * 8;
    memset(pc, 0, 16);
    for (int i = 0; i < 8; i++) pc[i] = (unsigned char)(ab >> (56 - 8*i));
    for (int i = 0; i < 8; i++) pc[8 + i] = (unsigned char)(cb >> (56 - 8*i));
    pc += 16;
    size_t nf = (size_t)(pc - flux) / 16;
    unsigned char Y[16]; memset(Y, 0, 16);
    for (size_t b = 0; b < nf; b++) {
        unsigned char tmp[16];
        for (int i = 0; i < 16; i++) tmp[i] = Y[i] ^ flux[16*b + i];
        appeler_r10(fn_ghash, (unsigned long)(0x500800), (unsigned long)tmp,
                    (unsigned long)H, 0, 0, pclmul ? 1 : 0);
        memcpy(Y, (void*)0x500800, 16);
    }
    for (int i = 0; i < 16; i++) tag[i] = EJ0[i] ^ Y[i];
    free(cbs); free(ks); free(flux);
}

static int evp_gcm(const unsigned char *cle, int bits,
                   const unsigned char *nonce, const unsigned char *clair, size_t n,
                   const unsigned char *aad, size_t na,
                   unsigned char *ct, unsigned char *tag) {
    const EVP_CIPHER *c = bits == 128 ? EVP_aes_128_gcm() : EVP_aes_256_gcm();
    EVP_CIPHER_CTX *x = EVP_CIPHER_CTX_new();
    int l;
    EVP_EncryptInit_ex(x, c, NULL, NULL, NULL);
    EVP_CIPHER_CTX_ctrl(x, EVP_CTRL_GCM_SET_IVLEN, 12, NULL);
    EVP_EncryptInit_ex(x, NULL, NULL, cle, nonce);
    EVP_EncryptUpdate(x, NULL, &l, aad, na);
    EVP_EncryptUpdate(x, ct, &l, clair, n);
    EVP_EncryptFinal_ex(x, ct + n, &l);
    EVP_CIPHER_CTX_ctrl(x, EVP_CTRL_GCM_GET_TAG, 16, tag);
    EVP_CIPHER_CTX_free(x);
    return 0;
}

