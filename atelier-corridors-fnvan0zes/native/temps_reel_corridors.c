    __builtin___clear_cache((char*)0xC000, (char*)0x10000);
    __builtin___clear_cache((char*)0x2F00, (char*)0x3000);

    /* ---- LA DIFFÉRENTIELLE NATIVE : l'hybride et l'AVX2 (le vrai dispatch) */
    long div_hyb = 0, div_avx = 0;
    for (int i = 0; i < NB_VECS; i++) {
        long attendu = (long)memmem((TAMPONS + vec_decal[i]), vec_n[i], (MOTIFS + m_decal[i]), vec_lm[i]);
        long attendu_idx = (attendu == 0 && vec_lm[i] > 0 && (TAMPONS + vec_decal[i])[0] == (MOTIFS + m_decal[i])) ? 0 :
            (attendu ? (attendu - (long)(TAMPONS + vec_decal[i])) : -1);
        /* le juge honnête : memmem sur des tampons NUL-terminés artificiels
           est piégeux — le jugement porté par memcmp séquentiel */
        long juge = -1;
        for (long p = 0; p + vec_lm[i] <= vec_n[i]; p++) {
            if (memcmp((TAMPONS + vec_decal[i]) + p, (MOTIFS + m_decal[i]), vec_lm[i]) == 0) { juge = p; break; }
        }
        (void)attendu_idx;
        long r_h = appeler_msx64(0xCD00, (unsigned long)(TAMPONS + vec_decal[i]), vec_n[i],
                                 (unsigned long)(MOTIFS + m_decal[i]), vec_lm[i], 0);
        long r_a = appeler_msx64(0xD100, (unsigned long)(TAMPONS + vec_decal[i]), vec_n[i],
                                 (unsigned long)(MOTIFS + m_decal[i]), vec_lm[i], 0);
        if (vec_lm[i] > 32) {
            /* LE REFUS DE CONTRAT (P2 : le motif ≤ 0x20) — attendu -5 */
            if (r_h != -5) div_hyb++;
            if (r_a != -5) div_avx++;
        } else {
            if (r_h != juge) div_hyb++;
            if (r_a != juge) div_avx++;
        }
    }
    printf("LA DIFFÉRENTIELLE NATIVE : hybride %ld/%d divergences ; AVX2 %ld/%d divergences\n",
           div_hyb, NB_VECS, div_avx, NB_VECS);

